/* =========================
   MOSTRAR LOS REGALOS
========================= */

const giftContainer = document.getElementById("giftContainer");
const searchInput = document.getElementById("searchInput");
const emptyMessage = document.getElementById("emptyMessage");


function renderGifts(products) {

    giftContainer.innerHTML = "";

    products.forEach((gift, index) => {

        const card = document.createElement("article");

        card.className = "gift-card";

        card.style.animationDelay = `${index * 0.12}s`;

        card.innerHTML = `

            <div class="gift-image">

                <img
                    src="${gift.image}"
                    alt="${gift.name}"
                    loading="lazy"
                >

            </div>

            <div class="gift-info">

                <p class="gift-category">
                    ${gift.category}
                </p>

                <h3>${gift.name}</h3>

                <p class="gift-description">
                    ${gift.description}
                </p>

                <div class="gift-bottom">

                    <span class="gift-price">
                        ${formatPrice(gift.price)}
                    </span>

                    <a
                        href="${gift.store}"
                        target="_blank"
                        rel="noopener noreferrer"
                        class="buy-button"
                    >
                        VER REGALO ↗
                    </a>

                </div>

            </div>

        `;

        giftContainer.appendChild(card);

    });

    emptyMessage.hidden = products.length !== 0;

}


/* =========================
   FORMATO DE PRECIOS
========================= */

function formatPrice(price) {

    return new Intl.NumberFormat("es-MX", {
        style: "currency",
        currency: "MXN"
    }).format(price);

}


/* =========================
   BUSCADOR DE REGALOS
========================= */

searchInput.addEventListener("input", () => {

    const search = searchInput.value
        .toLowerCase()
        .trim();

    const filteredGifts = gifts.filter(gift => {

        return (
            gift.name.toLowerCase().includes(search) ||
            gift.category.toLowerCase().includes(search) ||
            gift.description.toLowerCase().includes(search)
        );

    });

    renderGifts(filteredGifts);

});


/* =========================
   INICIAR CATÁLOGO
========================= */

renderGifts(gifts);
